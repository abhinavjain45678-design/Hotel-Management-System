/**
 * Pure billing and business rule calculations matching the Java Core project logic
 * (Bill.java, OrderService.java, FileHandlerUtil.java)
 */

export interface OrderItemCalculation {
  id: number;
  name: string;
  price: number;
  quantity: number;
  category: string;
}

export interface BillingSummary {
  subtotal: number;
  discountPercent: number;
  discountAmount: number;
  taxableAmount: number;
  cgstRate: number; // 2.5% default for food
  cgstAmount: number;
  sgstRate: number; // 2.5% default for food
  sgstAmount: number;
  totalTax: number;
  grandTotal: number;
  roundOff: number;
  payableAmount: number;
}

export const CGST_PERCENT = 2.5;
export const SGST_PERCENT = 2.5;

export function calculateSubtotal(items: OrderItemCalculation[]): number {
  if (!items || items.length === 0) return 0;
  return items.reduce((sum, item) => sum + item.price * Math.max(0, item.quantity), 0);
}

export function calculateBilling(
  items: OrderItemCalculation[],
  discountPercent = 0,
  loyaltyDiscount = 0
): BillingSummary {
  const subtotal = calculateSubtotal(items);
  const percentDiscountAmount = (subtotal * Math.min(100, Math.max(0, discountPercent))) / 100;
  const totalDiscount = Math.min(subtotal, percentDiscountAmount + loyaltyDiscount);
  const taxableAmount = Math.max(0, subtotal - totalDiscount);

  const cgstAmount = Number(((taxableAmount * CGST_PERCENT) / 100).toFixed(2));
  const sgstAmount = Number(((taxableAmount * SGST_PERCENT) / 100).toFixed(2));
  const totalTax = Number((cgstAmount + sgstAmount).toFixed(2));

  const exactGrandTotal = taxableAmount + totalTax;
  const payableAmount = Math.round(exactGrandTotal);
  const roundOff = Number((payableAmount - exactGrandTotal).toFixed(2));

  return {
    subtotal: Number(subtotal.toFixed(2)),
    discountPercent,
    discountAmount: Number(totalDiscount.toFixed(2)),
    taxableAmount: Number(taxableAmount.toFixed(2)),
    cgstRate: CGST_PERCENT,
    cgstAmount,
    sgstRate: SGST_PERCENT,
    sgstAmount,
    totalTax,
    grandTotal: exactGrandTotal,
    roundOff,
    payableAmount,
  };
}

export function validateCustomer(name: string, phone: string): { valid: boolean; error?: string } {
  if (!name || name.trim().length < 2) {
    return { valid: false, error: 'Customer name must be at least 2 characters long.' };
  }
  const cleanPhone = phone.replace(/[\s-]/g, '');
  if (!cleanPhone || cleanPhone.length < 8 || !/^\+?\d{8,15}$/.test(cleanPhone)) {
    return { valid: false, error: 'Customer phone must be between 8 and 15 digits.' };
  }
  return { valid: true };
}

export function formatAsciiReceipt(
  billId: string,
  orderId: number,
  tableNo: number,
  customerName: string,
  customerPhone: string,
  items: OrderItemCalculation[],
  summary: BillingSummary,
  paymentMode: string,
  dateTimeStr: string
): string {
  const line = '='.repeat(48);
  const dash = '-'.repeat(48);

  const itemLines = items
    .map((item) => {
      const total = (item.price * item.quantity).toFixed(2);
      const name = item.name.length > 22 ? item.name.substring(0, 20) + '..' : item.name;
      return `${name.padEnd(23)} ${String(item.quantity).padStart(3)} x ${item.price.toFixed(0).padStart(4)} = ${total.padStart(9)}`;
    })
    .join('\n');

  return `
${line}
             GRAND PALACE RESTAURANT & HOTEL
            NH-48, Heritage Way, Sector 12
                 GSTIN: 07AAAAA0000A1Z5
                  Phone: +91 98765 43210
${line}
 INVOICE #: ${billId.padEnd(16)} ORDER #: ${orderId}
 DATE/TIME: ${dateTimeStr}
 TABLE NO : Table ${tableNo}
 CUSTOMER : ${customerName} (${customerPhone})
 CASHIER  : Admin / Java POS Desk
${dash}
 ITEM                     QTY   PRICE      TOTAL
${dash}
${itemLines}
${dash}
 Subtotal:                                ₹${summary.subtotal.toFixed(2).padStart(8)}
 Discount Applied:                       -₹${summary.discountAmount.toFixed(2).padStart(8)}
 Taxable Amount:                          ₹${summary.taxableAmount.toFixed(2).padStart(8)}
 CGST (${summary.cgstRate}%):                              ₹${summary.cgstAmount.toFixed(2).padStart(8)}
 SGST (${summary.sgstRate}%):                              ₹${summary.sgstAmount.toFixed(2).padStart(8)}
 Round Off:                               ₹${summary.roundOff >= 0 ? '+' : ''}${summary.roundOff.toFixed(2).padStart(7)}
${line}
 NET PAYABLE AMOUNT:                      ₹${summary.payableAmount.toFixed(2).padStart(8)}
 PAYMENT MODE: ${paymentMode.toUpperCase()} [PAID]
${line}
       THANK YOU FOR DINING WITH US! VISIT AGAIN!
          Generated by GrandPalace Core Java POS
       File Stored at: /invoices/${billId}.txt
${line}`.trim();
}
